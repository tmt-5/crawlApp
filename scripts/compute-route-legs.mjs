// Computes walking legs between the stops of every published route and writes
// them as a SQL data migration (see supabase/migrations/0006_route_legs.sql).
//
//   node scripts/compute-route-legs.mjs [output.sql]
//
// Reads routes from Supabase with the public anon key (read only) and asks the
// FOSSGIS OSRM foot router for each leg. That server is for light use only,
// which is why legs are computed here once instead of in the app.

import { writeFileSync } from "node:fs";

process.loadEnvFile(".env");

const SUPABASE_URL = process.env.EXPO_PUBLIC_SUPABASE_URL;
const SUPABASE_KEY = process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY;
const OSRM_FOOT = "https://routing.openstreetmap.de/routed-foot/route/v1/driving";
const OUTPUT = process.argv[2] ?? "supabase/migrations/0007_route_legs_data.sql";

const round = (n, digits) => Number(n.toFixed(digits));
const sqlText = (value) => `'${String(value).replaceAll("'", "''")}'`;
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function fetchRoutes() {
  const select = "slug,city,name,stops:route_venues(order_index,venue:venues(name,latitude,longitude))";
  const res = await fetch(`${SUPABASE_URL}/rest/v1/routes?select=${encodeURIComponent(select)}`, {
    headers: { apikey: SUPABASE_KEY, Authorization: `Bearer ${SUPABASE_KEY}` },
  });
  if (!res.ok) throw new Error(`Supabase ${res.status}: ${await res.text()}`);
  const routes = await res.json();
  for (const route of routes) route.stops.sort((a, b) => a.order_index - b.order_index);
  return routes;
}

async function walkingLeg(from, to) {
  const coords = `${from.longitude},${from.latitude};${to.longitude},${to.latitude}`;
  const res = await fetch(`${OSRM_FOOT}/${coords}?overview=full&geometries=geojson&steps=true`, {
    headers: { "User-Agent": "crawl-route-legs/1.0 (one-off precompute)" },
  });
  const body = await res.json();
  if (body.code !== "Ok") throw new Error(`OSRM: ${body.code} ${body.message ?? ""}`);
  const route = body.routes[0];
  return {
    geometry: route.geometry.coordinates.map(([lng, lat]) => [round(lng, 6), round(lat, 6)]),
    distance: Math.round(route.distance),
    duration: Math.round(route.duration),
    steps: route.legs[0].steps.map((step) => ({
      type: step.maneuver.type,
      modifier: step.maneuver.modifier ?? null,
      name: step.name || null,
      distance: Math.round(step.distance),
      duration: Math.round(step.duration),
      location: step.maneuver.location.map((n) => round(n, 6)),
    })),
  };
}

const routes = await fetchRoutes();
const statements = [];

for (const route of routes) {
  for (let i = 1; i < route.stops.length; i++) {
    const from = route.stops[i - 1].venue;
    const to = route.stops[i].venue;
    if (from.latitude == null || to.latitude == null) {
      console.warn(`skip ${route.slug}: ${from.name} → ${to.name} (missing coordinates)`);
      continue;
    }
    const leg = await walkingLeg(from, to);
    console.log(`${route.slug}: ${from.name} → ${to.name} · ${leg.distance} m · ${Math.round(leg.duration / 60)} min`);
    statements.push(`update route_venues rv set
  leg_geometry = ${sqlText(JSON.stringify(leg.geometry))}::jsonb,
  leg_distance_m = ${leg.distance},
  leg_duration_s = ${leg.duration},
  leg_steps = ${sqlText(JSON.stringify(leg.steps))}::jsonb
from routes r, venues v
where rv.route_id = r.id and rv.venue_id = v.id
  and r.city = ${sqlText(route.city)} and r.slug = ${sqlText(route.slug)}
  and v.name = ${sqlText(to.name)};`);
    await sleep(1000);
  }
}

writeFileSync(
  OUTPUT,
  `-- Generated by scripts/compute-route-legs.mjs. Walking legs from OSRM (FOSSGIS foot profile).\n-- Re-run the script after changing a route's stops.\n\n${statements.join("\n\n")}\n`
);
console.log(`Wrote ${statements.length} legs to ${OUTPUT}`);
